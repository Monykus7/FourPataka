import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const reviewed = new Set(['MIT', 'ISC', 'OFL-1.1']);
const normalized = (text) => text.replace(/\r\n/g, '\n').trimEnd() + '\n';

export async function collectNotices(root) {
  const lock = JSON.parse(await readFile(resolve(root, 'package-lock.json'), 'utf8'));
  const sections = [];
  // Lockfile flags include transitives and nested installs; direct dependencies
  // alone would omit licenses for code bundled by Vite.
  for (const [directory, entry] of Object.entries(lock.packages).sort(([a], [b]) =>
    a < b ? -1 : a > b ? 1 : 0,
  )) {
    if (!directory || entry.dev || entry.devOptional) continue;
    if (!/^node_modules\/(?:[^/]+\/)*[^/]+$/.test(directory) || directory.split('/').includes('..'))
      throw new Error(`Invalid installed package path: ${directory}`);
    if (!reviewed.has(entry.license))
      throw new Error(`License review required: ${directory} (${entry.license})`);
    const folder = resolve(root, directory);
    const pkg = JSON.parse(await readFile(resolve(folder, 'package.json'), 'utf8'));
    if (pkg.version !== entry.version || pkg.license !== entry.license)
      throw new Error(`Installed metadata differs from lockfile: ${directory}`);
    const files = (await readdir(folder, { withFileTypes: true }))
      .filter((file) => file.isFile() && /^(licen[cs]e|copying|notice)([._-].*)?$/i.test(file.name))
      .map((file) => file.name)
      .sort();
    if (!files.length) throw new Error(`Missing license text: ${directory}`);
    const texts = await Promise.all(
      files.map(async (file) => {
        const text = normalized(await readFile(resolve(folder, file), 'utf8'));
        if (text.trim().length < 40) throw new Error(`Empty license: ${directory}/${file}`);
        return `--- ${file} ---\n${text}`;
      }),
    );
    sections.push(`${pkg.name}@${pkg.version} (${entry.license})\n${texts.join('\n')}`);
  }
  return (
    'FourPataka shipped application dependencies\nGenerated by npm run licenses:build; retain complete notices.\n\n' +
    sections.join('\n====================\n\n')
  );
}

export async function updateNotices(root, check) {
  const outputs = {
    'public/THIRD_PARTY_LICENSES.txt': await collectNotices(root),
    'public/LICENSE.txt': normalized(await readFile(resolve(root, 'LICENSE'), 'utf8')),
  };
  for (const [file, contents] of Object.entries(outputs)) {
    if (check) {
      let existing = '';
      try {
        existing = await readFile(resolve(root, file), 'utf8');
      } catch (error) {
        if (error.code !== 'ENOENT') throw error;
      }
      if (normalized(existing) !== normalized(contents))
        throw new Error(`${file} is stale; run npm run licenses:build and review the diff`);
    } else {
      await mkdir(resolve(root, 'public'), { recursive: true });
      await writeFile(resolve(root, file), contents, 'utf8');
    }
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await updateNotices(process.cwd(), process.argv.includes('--check'));
  console.log(
    process.argv.includes('--check')
      ? 'Shipped notices match installed dependencies.'
      : 'Shipped notices updated.',
  );
}
